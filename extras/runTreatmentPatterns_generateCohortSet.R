# ==============================================================================
# PioneerTriptorelin — Treatment Patterns via generateCohortSet (Redshift, no DuckDB)
# Structured after the darwin-eu/TreatmentPatterns vignette a010_Computing_Pathways.
#
# The vignette always builds the cohort table with CDMConnector::generateCohortSet
# (a proper omopgenerics cohort table). Reproducing an existing cohort table by
# hand (dplyr::tbl / newCohortTable) did not build a treatment history, so this
# script does exactly what the vignette does: it regenerates the target + event
# cohorts FROM their JSON definitions against the CDM with generateCohortSet(),
# then computes pathways on that table.
#
# Runs directly on Redshift via DatabaseConnector (no DuckDB). Temp tables are
# routed through emulation into the writable cohort schema, because CDMConnector's
# native #temp path fails on this Redshift.
#
# Note: generateCohortSet re-executes the cohort SQL against the CDM, so this can
# take several minutes (it rebuilds the mPC-triptorelin + 6 ADT-agent cohorts).
# ==============================================================================

library(dplyr)
library(DatabaseConnector)
library(CDMConnector)
library(TreatmentPatterns)

# ------------------------------------------------------------------------------
# 0. Parameters  (edit to match your site / codeToRun.R)
# ------------------------------------------------------------------------------
source("../credentials.r")   # DBMS, USER, PASSWORD, SERVER, DB_PORT

JDBC <- "/home/a_kiselev/Jdbc"
connectionDetails <- DatabaseConnector::createConnectionDetails(
  dbms = DBMS, user = USER, password = PASSWORD,
  server = SERVER, port = DB_PORT, pathToDriver = JDBC
)

cdmDatabaseSchema    <- "marketscan_ccaemdcr_aug2025"
cohortDatabaseSchema <- "marketscan_ccaemdcr_aug2025_results"
tpCohortTable        <- "tp_cohort_table"   # NEW table generated by this script

targetCohortId <- 1751
eventCohortIds <- c(1758, 1759, 1760, 1761, 1762, 1763)

databaseId   <- "MarketScan"
databaseName <- "MarketScan aug2025"
minCellCount <- 5

outputFolder <- file.path("/home/a_kiselev/output", paste0(databaseId, "_triptorelin"))

# Pathway-construction settings
minEraDuration             <- 0
eraCollapseSize            <- 30
combinationWindow          <- 30
minPostCombinationDuration <- 30
filterTreatments           <- "First"
maxPathLength              <- 5
addNoPaths                 <- FALSE

# ------------------------------------------------------------------------------
# Derived
# ------------------------------------------------------------------------------
allIds    <- c(targetCohortId, eventCohortIds[!is.na(eventCohortIds)])
tpFolder  <- file.path(outputFolder, "treatmentPatterns")
csvFolder <- file.path(tpFolder, "output")
defDir    <- file.path(tpFolder, "cohortDefs")
dir.create(csvFolder, recursive = TRUE, showWarnings = FALSE)
dir.create(defDir,    recursive = TRUE, showWarnings = FALSE)

# Redshift: native #temp tables fail through CDMConnector's write path; route
# temp tables through emulation into the writable cohort schema.
options(sqlRenderTempEmulationSchema = cohortDatabaseSchema)

# ------------------------------------------------------------------------------
# 1. Connect + build the cdm reference (full Redshift CDM)
# ------------------------------------------------------------------------------
con <- DatabaseConnector::connect(connectionDetails)
on.exit(DatabaseConnector::disconnect(con), add = TRUE)

cdm <- CDMConnector::cdmFromCon(
  con = con, cdmSchema = cdmDatabaseSchema, writeSchema = cohortDatabaseSchema,
  cdmName = databaseName, .softValidation = TRUE
)

# ------------------------------------------------------------------------------
# 2. Read the cohort definitions (target + events) and generate the cohort table
#    Copy just the 7 JSONs into a temp folder so readCohortSet reads only these.
# ------------------------------------------------------------------------------
srcCohorts <- system.file("cohorts", package = "PioneerTriptorelin")
for (id in allIds) {
  file.copy(file.path(srcCohorts, paste0(id, ".json")),
            file.path(defDir,     paste0(id, ".json")), overwrite = TRUE)
}

cohortSet <- CDMConnector::readCohortSet(path = defDir)
message("readCohortSet:")
print(cohortSet[, c("cohort_definition_id", "cohort_name")])

message("Generating cohorts with generateCohortSet() (this can take a while) ...")
cdm <- CDMConnector::generateCohortSet(
  cdm = cdm, cohortSet = cohortSet, name = tpCohortTable, overwrite = TRUE
)
print(CDMConnector::cohortCount(cdm[[tpCohortTable]]))

# ------------------------------------------------------------------------------
# 3. cohorts data.frame for computePathways (cohortId / cohortName / type)
#    readCohortSet uses the file name ("1751", ...) as cohort_name and assigns a
#    fresh cohort_definition_id (1..n); map those to the real names + target/event.
# ------------------------------------------------------------------------------
cohortsToCreate <- readr::read_csv(
  system.file("settings", "CohortsToCreate.csv", package = "PioneerTriptorelin"),
  col_types = readr::cols())
nameMap <- setNames(cohortsToCreate$cohort_name, as.character(cohortsToCreate$cohortId))

cohorts <- cohortSet %>%
  dplyr::transmute(
    cohortId   = .data$cohort_definition_id,
    cohortName = unname(nameMap[as.character(.data$cohort_name)]),
    type       = ifelse(as.character(.data$cohort_name) == as.character(targetCohortId),
                        "target", "event")
  ) %>%
  as.data.frame()
message("cohorts:")
print(cohorts)

# ------------------------------------------------------------------------------
# 4. Compute pathways + export
# ------------------------------------------------------------------------------
message("Computing pathways ...")
outputEnv <- TreatmentPatterns::computePathways(
  cohorts                    = cohorts,
  cohortTableName            = tpCohortTable,
  cdm                        = cdm,
  analysisId                 = 1,
  description                = databaseName,
  startAnchor                = "startDate",
  windowStart                = 0,
  endAnchor                  = "endDate",
  windowEnd                  = 0,
  minEraDuration             = minEraDuration,
  eraCollapseSize            = eraCollapseSize,
  combinationWindow          = combinationWindow,
  minPostCombinationDuration = minPostCombinationDuration,
  filterTreatments           = filterTreatments,
  maxPathLength              = maxPathLength
)

results <- TreatmentPatterns::export(
  andromeda    = outputEnv,
  outputPath   = csvFolder,
  minCellCount = minCellCount,
  censorType   = "minCellCount",
  nonePaths    = addNoPaths
)
message("Pathways rows: ", nrow(results$treatment_pathways),
        "  |  CSVs written to ", csvFolder)

# ------------------------------------------------------------------------------
# 5. Save interactive sunburst + Sankey as standalone HTML (best effort)
# ------------------------------------------------------------------------------
if (requireNamespace("htmlwidgets", quietly = TRUE) &&
    nrow(results$treatment_pathways) > 0) {
  tryCatch({
    htmlwidgets::saveWidget(results$plotSunburst(),
                            file.path(tpFolder, "sunburst.html"), selfcontained = TRUE)
    htmlwidgets::saveWidget(results$plotSankey(),
                            file.path(tpFolder, "sankey.html"),   selfcontained = TRUE)
    message("Saved sunburst.html and sankey.html to ", tpFolder)
  }, error = function(e) message("Could not save plots: ", conditionMessage(e)))
}

try(Andromeda::close(outputEnv), silent = TRUE)
message("Done.")
